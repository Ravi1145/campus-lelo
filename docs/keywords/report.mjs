// Build docs/MBA_KEYWORD_CLUSTERS.md from the harvest + clustering output.
// Run after harvest.mjs and cluster.mjs:  node docs/keywords/report.mjs
import fs from "node:fs"
import path from "node:path"

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"))
const root = path.resolve(here, "../..")
const raw = JSON.parse(fs.readFileSync(path.join(here, "raw-suggestions.json"), "utf8"))
const clusters = JSON.parse(fs.readFileSync(path.join(here, "mba-clusters.json"), "utf8"))
const csv = fs.readFileSync(path.join(here, "mba-keywords.csv"), "utf8").replace(/^﻿/, "").split("\n").slice(1).filter(Boolean)
const parse = (line) => { const out = []; let cur = "", q = false; for (let i = 0; i < line.length; i++) { const ch = line[i]; if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++ } else if (ch === '"') q = false; else cur += ch } else if (ch === '"') q = true; else if (ch === ",") { out.push(cur); cur = "" } else cur += ch } out.push(cur); return out }
const rows = csv.map(parse).map(([keyword, cluster, topic, location, exam, spec, intent, funnel, signal, url, status]) => ({ keyword, cluster, topic, location, exam, spec, intent, funnel, signal: +signal, url, status }))

const tally = (key) => { const m = {}; rows.forEach((r) => { const k = r[key] || "(none)"; m[k] = (m[k] ?? 0) + 1 }); return Object.entries(m).sort((a, b) => b[1] - a[1]) }
const tbl = (head, data) => `| ${head.join(" | ")} |\n| ${head.map(() => "---").join(" | ")} |\n${data.map((r) => `| ${r.join(" | ")} |`).join("\n")}`
const pct = (n) => `${Math.round((n / rows.length) * 100)}%`
const covered = rows.filter((r) => r.url).length

const articles = clusters.filter((c) => c.article)
const byArticle = new Map()
for (const c of articles) { if (!byArticle.has(c.pillar)) byArticle.set(c.pillar, []); byArticle.get(c.pillar).push(c) }
const gaps = clusters.filter((c) => !c.pillar)

const md = `# MBA / PGDM keyword research, clusters and interlinking

_Generated by \`docs/keywords/harvest.mjs\` → \`cluster.mjs\` → \`report.mjs\`. Re-run all three to refresh._

## 1. How the keywords were found

- **Source:** Google India autocomplete (\`suggestqueries.google.com\`, \`hl=en\`, \`gl=in\`) — the queries people actually type.
- **Seeds (${Object.keys(raw).length ? "see harvest.mjs" : ""}):** 10 cities × 27 topics, 11 exams × 13 topics, 12 specialisations, 20 colleges × 8 topics, ~50 general questions, plus A–Z expansion of 14 head terms for long-tail queries.
- **Result:** ${Object.keys(raw).length.toLocaleString()} unique suggestions → **${rows.length.toLocaleString()} relevant MBA/PGDM queries** after filtering.
- **Limits — read this:** autocomplete shows *what is searched*, not *how often*. There is no search-volume column. \`signal\` in the CSV is only the suggestion position and how many seeds produced the query. For volumes and difficulty, add Search Console (your own site) or a paid tool (Ahrefs/Semrush) and join on \`keyword\`.

## 2. Segmentation

Every query is tagged on four independent axes (see \`mba-keywords.csv\`).

**By topic (what the searcher wants)**

${tbl(["Topic", "Queries", "Share"], tally("topic").map(([k, n]) => [k, n, pct(n)]))}

**By location**

${tbl(["Location", "Queries", "Share"], tally("location").map(([k, n]) => [k, n, pct(n)]))}

**By entrance exam**

${tbl(["Exam", "Queries"], tally("exam").filter(([k]) => k !== "(none)").map(([k, n]) => [k, n]))}

**By search intent and funnel stage**

${tbl(["Intent", "Funnel stage", "Queries", "Share"], tally("intent").map(([k, n]) => [k, rows.find((r) => r.intent === k)?.funnel ?? "", n, pct(n)]))}

## 3. Clusters

${clusters.length} clusters (topic × city, or exam × topic). Clusters with a page that covers ≥ 50% of their queries use that page as the **pillar**; the rest are served by a new article (section 4) or listed as gaps (section 5). **${covered.toLocaleString()} of ${rows.length.toLocaleString()} queries (${pct(covered)}) now have a target page or article** — ${rows.filter((r) => r.status === "page exists").length.toLocaleString()} match an existing page exactly, ${rows.filter((r) => r.status === "new article").length.toLocaleString()} are served by the new articles and ${rows.filter((r) => r.status === "cluster pillar").length.toLocaleString()} by their cluster's pillar page.

${tbl(
  ["Cluster", "Queries", "Intent", "Pillar page", "Supporting pages", "Top real queries"],
  clusters.filter((c) => c.pillar).map((c) => [c.name, c.size, c.intent, c.pillar, c.supporting.join("<br>") || "—", c.keywords.slice(0, 3).join("; ")]),
)}

## 4. New articles (written for clusters that had no page)

${tbl(
  ["Article", "Serves clusters", "Queries covered", "Example real queries"],
  [...byArticle.entries()].map(([url, cs]) => [url, cs.map((c) => c.id).join("<br>"), cs.reduce((s, c) => s + c.size, 0), cs[0].keywords.slice(0, 4).join("; ")]),
)}

Writing rules: no fee, package, cut-off or date is written by hand. Exam facts (conducting body, frequency, eligibility, dates, scoring, published cut-offs) are generated from the sourced files in \`src/data/mba/\`; everything else is method and explanation, with official links.

## 5. Gaps still open (no page)

${tbl(["Cluster", "Queries", "Why not covered", "Example queries"], gaps.map((c) => [c.id, c.size, /mumbai|bangalore|hyderabad/.test(c.id) ? "City outside the current Pune / Noida / Delhi NCR focus" : c.id.startsWith("exam:cuet-pg") ? "CUET PG for MBA needs official-source verification first" : "Mixed brand/general queries — need dedicated college pages with verified data", c.keywords.slice(0, 3).join("; ")]))}

## 6. Interlinking architecture

- **Hub:** \`/mba\` links every pillar, city, exam, specialisation and guide, grouped by segment. Linked from the header MBA menu and from every related-searches block.
- **Related searches block** (\`RelatedMbaSearches\`) on all MBA pages — Pune cluster pages, city × exam pages, Noida and Delhi NCR pages, exam hubs and topic pages, and the MBA articles. Chips are real queries; each links to the best page for that query:
  1. clusters that share the page's **topic** in other cities (e.g. Pune fees → Noida fees, national fees guide),
  2. clusters that share its **city** with other topics,
  3. clusters that share its **exam**,
  4. national guides get a small boost so every page links up to a guide.
- **Articles ↔ pages:** each article links to the city pages, exam guides and its sibling articles in the text, and ends with "Related guides".
- **Meta keywords:** \`generateMetadata\` merges each page's own cluster queries into \`<meta name="keywords">\` (low SEO value for Google, kept for other engines and tooling). The on-page value is the headings and links above.

## 7. Files

| File | Purpose |
| --- | --- |
| \`docs/keywords/raw-suggestions.json\` | Raw harvest (query → seeds, best rank) |
| \`docs/keywords/mba-keywords.csv\` | Every query with cluster, topic, location, exam, intent, funnel, target URL, status |
| \`docs/keywords/mba-clusters.json\` | Full cluster list incl. gaps |
| \`src/data/mba/keywordClusters.ts\` | Compact data used by the site (generated) |
| \`src/lib/mbaKeywords.ts\` | Meta keywords, related searches, hub grouping |
| \`src/components/mba/RelatedMbaSearches.tsx\` | Interlinking block |
| \`src/data/blog-posts/mba-india-guides.ts\` | The ten national articles |
| \`src/app/mba/page.tsx\` | Hub page |

## 8. Next steps

1. Connect Search Console and join real clicks/impressions to \`mba-keywords.csv\` to rank clusters by traffic potential.
2. Verify CUET PG for MBA from NTA / university notices, then add an exam guide.
3. Mumbai, Bangalore and Hyderabad pages once the Pune / Noida / NCR set is done (≈ 1,100 queries).
4. College-specific pages (IIFT, BIMTECH, Jaipuria, SIBM, SCMHRD, MIT-WPU) from \`programAdmissions.ts\` — brand queries are the largest unserved group after the national guides.
5. Re-run the harvest each admission cycle; new exam-date queries appear after each notification.
`
fs.writeFileSync(path.join(root, "docs/MBA_KEYWORD_CLUSTERS.md"), md)
console.log("wrote docs/MBA_KEYWORD_CLUSTERS.md", md.length, "chars; covered", covered, "of", rows.length)
