// Generates src/data/clusterPools.ts: the indexable pages of each topic cluster, used to spread internal links.
// Run after adding or retiring pages:  node scripts/gen-cluster-pools.mjs
import fs from "node:fs"
import path from "node:path"

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..")
const dirs = fs.readdirSync(path.join(root, "src/app"), { withFileTypes: true }).filter((d) => d.isDirectory() && fs.existsSync(path.join(root, "src/app", d.name, "page.tsx"))).map((d) => d.name)

const retired = new Set([...fs.readFileSync(path.join(root, "src/data/retiredPages.ts"), "utf8").matchAll(/source:\s*"(\/[a-z0-9-]+)"/g)].map((m) => m[1]))
const noindexSrc = fs.readFileSync(path.join(root, "src/data/noindexPages.ts"), "utf8")
const noindex = new Set([...noindexSrc.matchAll(/^\s*"(\/[a-z0-9/-]+)",/gm)].map((m) => m[1]))
const ok = (name) => !retired.has("/" + name) && !noindex.has("/" + name)

const pretty = (slug) =>
  slug.replace(/-/g, " ")
    .replace(/\bmba\b/gi, "MBA").replace(/\bpgdm\b/gi, "PGDM").replace(/\bbtech\b/gi, "BTech").replace(/\bpune\b/gi, "Pune")
    .replace(/\b(cat|xat|gmat|cmat|mat|snap|jee|mht cet|mh cet|nmat|atma)\b/gi, (m) => m.toUpperCase())
    .replace(/^./, (c) => c.toUpperCase())

const mba = dirs.filter((d) => ok(d) && (/^mba-colleges-in-pune-/.test(d) || ["mba-in-pune", "pgdm-in-pune", "pgdm-colleges-pune", "top-10-mba-colleges-in-pune", "best-mba-colleges-pune", "mba-colleges-pune", "private-mba-colleges-pune", "low-fees-mba-colleges-pune", "mba-colleges-in-pune", "mba-cutoff-pune", "mba-admission-process-pune", "mba-admission-pune-without-cat"].includes(d)))
const btech = dirs.filter((d) => ok(d) && (/^btech-/.test(d) || /^engineering-(colleges|admission)-pune/.test(d) || ["top-btech-colleges-in-pune", "best-btech-colleges-in-pune", "top-engineering-colleges-pune", "top-10-engineering-colleges-in-pune", "private-engineering-colleges-pune", "computer-engineering-colleges-pune", "mechanical-engineering-colleges-pune", "direct-admission-engineering-colleges-pune", "jee-colleges-pune", "mht-cet-colleges-pune"].includes(d)))

const entries = (list) => list.sort().map((d) => `  { href: "/${d}", label: ${JSON.stringify(pretty(d))} },`).join("\n")
const out = `// GENERATED by scripts/gen-cluster-pools.mjs. Do not edit by hand.
// Indexable pages of each topic cluster. MoreInCluster links each page to its next neighbours in the list,
// so every page in a cluster receives internal links.
export interface ClusterLink { href: string; label: string }

export const clusterPools: Record<"mba" | "btech", ClusterLink[]> = {
  mba: [
${entries(mba)}
  ],
  btech: [
${entries(btech)}
  ],
}
`
fs.writeFileSync(path.join(root, "src/data/clusterPools.ts"), out)
console.log("mba pool:", mba.length, "btech pool:", btech.length)
